package com.example.sis;

import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

@RestController
@RequestMapping("/api/students")
public class StudentController {

    // Convert a database row into a JSON-compatible map.
    private Map<String, Object> studentResult(ResultSet rs)
            throws SQLException {

        Map<String, Object> student = new LinkedHashMap<>();

        student.put("studentId", rs.getInt("StudentID"));
        student.put("rollNumber", rs.getString("RollNumber"));
        student.put("studentName", rs.getString("StudentName"));
        student.put("email", rs.getString("Email"));
        student.put("department", rs.getString("Department"));
        student.put("marks", rs.getDouble("Marks"));

        return student;
    }

    private Map<String, Object> error(String message) {
        Map<String, Object> result = new LinkedHashMap<>();
        result.put("message", message);
        return result;
    }

    private ResponseEntity<Map<String, Object>> databaseError(
            SQLException exception) {

        String detail = exception.getMessage() == null
                ? ""
                : exception.getMessage().toLowerCase();

        if (detail.contains("unique")) {
            return ResponseEntity.badRequest().body(
                    error("Roll number or email already exists.")
            );
        }

        exception.printStackTrace();

        return ResponseEntity.status(HttpStatus.INTERNAL_SERVER_ERROR)
                .body(error("A database error occurred."));
    }

    // INSERT: POST /api/students
    @PostMapping
    public ResponseEntity<Map<String, Object>> insertStudent(
            @RequestBody Map<String, Object> body) {

        try {
            validateStudent(body);

            String sql = """
                INSERT INTO Students
                (RollNumber, StudentName, Email, Department, Marks)
                VALUES (?, ?, ?, ?, ?)
                """;

            try (Connection connection =
                         StudentInformationSystem.getConnection();
                 PreparedStatement ps = connection.prepareStatement(sql)) {

                fillStatement(ps, body);
                ps.executeUpdate();

                // Get the ID generated by this connection.
                try (Statement statement = connection.createStatement();
                     ResultSet rs = statement.executeQuery(
                             "SELECT last_insert_rowid()")) {

                    rs.next();

                    Map<String, Object> result = new LinkedHashMap<>();
                    result.put("studentId", rs.getInt(1));
                    result.put("message", "Student inserted successfully.");

                    return ResponseEntity.status(HttpStatus.CREATED)
                            .body(result);
                }
            }

        } catch (IllegalArgumentException e) {
            return ResponseEntity.badRequest().body(error(e.getMessage()));

        } catch (SQLException e) {
            return databaseError(e);
        }
    }

    // SEARCH: GET /api/students/{id}
    @GetMapping("/{id}")
    public ResponseEntity<Map<String, Object>> searchStudent(
            @PathVariable("id") int id) {

        if (id <= 0) {
            return ResponseEntity.badRequest()
                    .body(error("Student ID must be positive."));
        }

        String sql = "SELECT * FROM Students WHERE StudentID = ?";

        try (Connection connection =
                     StudentInformationSystem.getConnection();
             PreparedStatement ps = connection.prepareStatement(sql)) {

            ps.setInt(1, id);

            try (ResultSet rs = ps.executeQuery()) {
                if (!rs.next()) {
                    return ResponseEntity.status(HttpStatus.NOT_FOUND)
                            .body(error("Student ID " + id + " not found."));
                }

                return ResponseEntity.ok(studentResult(rs));
            }

        } catch (SQLException e) {
            return databaseError(e);
        }
    }

    // UPDATE: PUT /api/students/{id}
    @PutMapping("/{id}")
    public ResponseEntity<Map<String, Object>> updateStudent(
            @PathVariable("id") int id,
            @RequestBody Map<String, Object> body) {

        if (id <= 0) {
            return ResponseEntity.badRequest()
                    .body(error("Student ID must be positive."));
        }

        try {
            validateStudent(body);

            String sql = """
                UPDATE Students
                SET RollNumber = ?,
                    StudentName = ?,
                    Email = ?,
                    Department = ?,
                    Marks = ?
                WHERE StudentID = ?
                """;

            try (Connection connection =
                         StudentInformationSystem.getConnection();
                 PreparedStatement ps = connection.prepareStatement(sql)) {

                fillStatement(ps, body);
                ps.setInt(6, id);

                int rowsUpdated = ps.executeUpdate();

                if (rowsUpdated == 0) {
                    return ResponseEntity.status(HttpStatus.NOT_FOUND)
                            .body(error("Student ID " + id + " not found."));
                }

                return ResponseEntity.ok(
                        error("Student updated successfully.")
                );
            }

        } catch (IllegalArgumentException e) {
            return ResponseEntity.badRequest().body(error(e.getMessage()));

        } catch (SQLException e) {
            return databaseError(e);
        }
    }

    // DELETE: DELETE /api/students/{id}
    @DeleteMapping("/{id}")
    public ResponseEntity<Map<String, Object>> deleteStudent(
            @PathVariable("id") int id) {

        if (id <= 0) {
            return ResponseEntity.badRequest()
                    .body(error("Student ID must be positive."));
        }

        String sql = "DELETE FROM Students WHERE StudentID = ?";

        try (Connection connection =
                     StudentInformationSystem.getConnection();
             PreparedStatement ps = connection.prepareStatement(sql)) {

            ps.setInt(1, id);

            int rowsDeleted = ps.executeUpdate();

            if (rowsDeleted == 0) {
                return ResponseEntity.status(HttpStatus.NOT_FOUND)
                        .body(error("Student ID " + id + " not found."));
            }

            return ResponseEntity.ok(
                    error("Student deleted successfully.")
            );

        } catch (SQLException e) {
            return databaseError(e);
        }
    }

    // Set values for INSERT and UPDATE.
    private void fillStatement(
            PreparedStatement ps,
            Map<String, Object> body) throws SQLException {

        ps.setString(1, body.get("rollNumber").toString().trim());
        ps.setString(2, body.get("studentName").toString().trim());
        ps.setString(3, body.get("email").toString().trim());
        ps.setString(4, body.get("department").toString().trim());

        ps.setDouble(
                5,
                Double.parseDouble(body.get("marks").toString())
        );
    }

    // Validate incoming form data.
    private void validateStudent(Map<String, Object> body) {
        String[] requiredFields = {
                "rollNumber",
                "studentName",
                "email",
                "department",
                "marks"
        };

        for (String field : requiredFields) {
            Object value = body.get(field);

            if (value == null || value.toString().trim().isEmpty()) {
                throw new IllegalArgumentException(
                        field + " is required."
                );
            }
        }

        String rollNumber = body.get("rollNumber").toString().trim();
        String studentName = body.get("studentName").toString().trim();
        String email = body.get("email").toString().trim();
        String department = body.get("department").toString().trim();

        if (rollNumber.length() > 30 ||
                studentName.length() > 100 ||
                email.length() > 150) {
            throw new IllegalArgumentException(
                    "One or more fields exceed their maximum length."
            );
        }

        if (!email.matches("^[^\\s@]+@[^\\s@]+\\.[^\\s@]+$")) {
            throw new IllegalArgumentException(
                    "Please enter a valid email address."
            );
        }

        if (!List.of("CSE", "AIML", "IT", "ECE").contains(department)) {
            throw new IllegalArgumentException(
                    "Please select a valid department."
            );
        }

        double marks;

        try {
            marks = Double.parseDouble(body.get("marks").toString());
        } catch (NumberFormatException e) {
            throw new IllegalArgumentException(
                    "Marks must be a valid number."
            );
        }

        if (!Double.isFinite(marks) || marks < 0 || marks > 100) {
            throw new IllegalArgumentException(
                    "Marks must be between 0 and 100."
            );
        }
    }
}